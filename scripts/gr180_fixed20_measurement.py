"""GR-180 fixed-20 reflection measurement: before/after precision on 20 fixed cases.

Runs the SHIPPED reflection pass (engine.review_profiles.FindingReflector,
commit 98d751cf) over exactly 20 fixed, repository-owned candidate findings —
the shape a second-pass reviewer produces — with a deterministic stub scorer,
and prints a before/after comparison:

    case count=20
    candidate findings before=20 after=20
    surviving findings before=20 after=13
    fabricated findings before=7 after=1
    precision before=0.6500 after=0.9231

WHAT "PRECISION" MEANS HERE — READ BEFORE QUOTING THE NUMBER:
The corpus carries NO independent human truth labels. The labels in CASES
(`correct` / `fabricated`) are FIXTURE TRUTH LABELS authored in this file, so
the precision figures are a clearly-labeled PROXY:

    precision = surviving findings labeled `correct` / surviving findings

`before` = the pipeline WITHOUT the reflection pass (every candidate survives;
that is the pre-GR-180 behavior). `after` = the same corpus through the actual
shipped `FindingReflector.reflect()` code path — real parsing, real
threshold comparison, real fail-closed drops — with only the model's scoring
call stubbed so the run needs no network and is byte-reproducible.

The stub scores are part of the fixture, one entry per candidate, and they
DELIBERATELY include two misses so the measurement is honest about what a
stub proves: case 12 (a `correct` finding the stub scores low — the filter
would drop a real finding) and case 19 (a `fabricated` finding the stub scores
high — the filter would keep a false one). This harness measures the FILTER
LOGIC's behavior over a labeled corpus; it does NOT measure live-model
reflection quality. That is GR-171 dry-run territory (review_dry_run.py), not
this artifact.

The measurement demonstrates: the shipped filter drops 6 of 7 labeled
fabricated findings while preserving 12 of 13 labeled correct findings, and
the label-proxy precision rises 0.6500 -> 0.9231. Fail-closed drops (cases
17/18: no score entry, unusable score) are exercised through the same real
code path.

Usage (deterministic, no network):
    .venv/bin/python scripts/gr180_fixed20_measurement.py

Exit 0 with the report on stdout; exit 1 if the case count is not exactly 20.
"""

