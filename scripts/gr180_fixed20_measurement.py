class StubReflectionLLM:
    """Deterministic stand-in for the reflection model.

    Returns the one canned score reply built from the fixture; never touches
    the network. Everything AFTER this reply — JSON parsing, per-finding score
    validation, the threshold comparison — is the shipped FindingReflector.
    """

    def __init__(self, reply: str) -> None:
        self.reply = reply
        self.calls = 0

    def chat(
        self, messages: object, tools: object = None, max_tokens: object = None
    ) -> LLMResponse:
        self.calls += 1
        return LLMResponse(content=self.reply, usage=LLMUsage())


def build_scores_reply(cases: list[dict]) -> str:
    """The stub reply: one score entry per case that has one, keyed by index.

    A case with score None is OMITTED from the list — that is the fail-closed
    "no score for finding i" path in reflect().
    """
    entries = []
    for i, case in enumerate(cases):
        if case["score"] is not None:
            entries.append({"index": i, **case["score"]})
    return json.dumps({"scores": entries, "summary": "fixed-20 stub scoring"}, sort_keys=True)


def measure(
    cases: list[dict] | None = None, threshold: float = DEFAULT_REFLECTION_THRESHOLD
) -> dict:
    """Run the shipped reflection pass over the fixed corpus; return the metrics.

    ``before`` is the no-reflection pipeline (every candidate survives — the
    pre-GR-180 behavior the pass was added to change). ``after`` is the result
    of FindingReflector.reflect() over the same candidates. Precision is the
    fixture-label PROXY: correct survivors / survivors.
    """
    corpus = cases if cases is not None else CASES
    findings = [SecondPassFinding(**case["finding"]) for case in corpus]

    reflector = FindingReflector(
        StubReflectionLLM(build_scores_reply(corpus)),
        workdir=str(REPO_ROOT),
        threshold=threshold,
    )
    result = reflector.reflect(findings, diff_text=FIXED_DIFF)

    # Map drops back to cases by the DROPPED FINDING'S INDEX — exact, since
    # reflect() records one DroppedFinding per dropped candidate. (Mapping by
    # finding content would collide: several cases legitimately cite the same
    # file:line, which is normal in a review corpus.) A case survives iff its
    # index is absent from result.dropped.
    dropped_indices = {d.index for d in result.dropped}
    outcomes = []
    for i, case in enumerate(corpus):
        outcomes.append(
            {"id": case["id"], "label": case["label"], "survived": i not in dropped_indices}
        )

    before_correct = sum(1 for c in corpus if c["label"] == "correct")
    before_fabricated = sum(1 for c in corpus if c["label"] == "fabricated")
    after_correct = sum(1 for o in outcomes if o["survived"] and o["label"] == "correct")
    after_fabricated = sum(1 for o in outcomes if o["survived"] and o["label"] == "fabricated")
    after_surviving = len(result.kept)

    return {
        "case_count": len(corpus),
        "threshold": threshold,
        "outcomes": outcomes,
        "dropped": result.dropped,
        "error": result.error,
        "candidates_before": len(corpus),
        "candidates_after": len(corpus),  # the filter never adds findings
        "surviving_before": len(corpus),
        "surviving_after": after_surviving,
        "fabricated_before": before_fabricated,
        "fabricated_after": after_fabricated,
        "correct_before": before_correct,
        "correct_after": after_correct,
        "precision_before": before_correct / len(corpus),
        "precision_after": (after_correct / after_surviving) if after_surviving else 0.0,
    }


def render(m: dict) -> str:
    """The report: required summary lines first, then the per-case ledger."""
    lines = [
        "GR-180 fixed-20 reflection measurement (shipped FindingReflector,"
        f" threshold {m['threshold']:.2f})",
        "labels are FIXTURE TRUTH LABELS; precision is a LABEL PROXY, not a human-judged claim",
        f"case count={m['case_count']}",
        f"candidate findings before={m['candidates_before']} after={m['candidates_after']}",
        f"surviving findings before={m['surviving_before']} after={m['surviving_after']}",
        f"fabricated findings before={m['fabricated_before']} after={m['fabricated_after']}",
        (f"precision before={m['precision_before']:.4f} after={m['precision_after']:.4f}"),
        "",
        "per-case ledger (label | stub score | expected | actual):",
    ]
    for case, outcome in zip(CASES, m["outcomes"]):
        score = case["score"]
        if score is None:
            score_text = "no score entry"
        else:
            score_text = f"{score['correctness']}/{score['evidence']}"
        lines.append(
            f"  {case['id']:<16} {case['label']:<9} {score_text:<24} "
            f"{case['expected_outcome']:<8} {'kept' if outcome['survived'] else 'dropped'}"
        )
    lines += [
        "",
        "drop reasons (fail-closed visibility, AC3):",
    ]
    for d in m["dropped"]:
        lines.append(f"  index {d.index} ({CASES[d.index]['id']}): {d.reason}")
    lines.append(f"  reflection error: {m['error']}")
    return "\n".join(lines)


def main() -> int:
    if len(CASES) != FIXED_CASE_COUNT:
        print(f"FATAL: case count {len(CASES)} != {FIXED_CASE_COUNT}", file=sys.stderr)
        return 1
    m = measure()
    print(render(m))
    return 0


if __name__ == "__main__":
    sys.exit(main())
